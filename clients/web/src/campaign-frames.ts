/**
 * The live campaign telemetry contract: a closed union of typed delta frames.
 *
 * This is the proposed wire projection described in
 * `docs/design/live-campaign-streaming.md`. Each frame is a small delta; folding
 * the stream in order reconstructs a `CampaignRecord`. The frames are the single
 * boundary between an untrusted source (a dev replay server today, the
 * orchestrator's projection later) and the typed client state.
 *
 * `parseCampaignFrame` validates once, here. Everything downstream (the fold and
 * the view) consumes typed values and never re-validates.
 */
import type {CampaignRecord, WorkstreamOutcome} from './campaign-record.js';

/** Mirrors the backend `WorkstreamPhase` StrEnum. A hand-written copy until the
 * backend emits these frames and the union is generated by `pnpm
 * generate:protocol`; see the design doc's "Backend path". */
export type WorkstreamPhase =
  | 'pending'
  | 'implementing'
  | 'implemented'
  | 'reviewed'
  | 'evaluated'
  | 'failed'
  | 'parked'
  | 'cancelled';

const WORKSTREAM_PHASES: readonly WorkstreamPhase[] = [
  'pending',
  'implementing',
  'implemented',
  'reviewed',
  'evaluated',
  'failed',
  'parked',
  'cancelled',
];

/** The campaign-level data known at (or declared for) the start of a run. */
export type CampaignHeader = Pick<
  CampaignRecord,
  | 'id'
  | 'title'
  | 'summary'
  | 'provenance'
  | 'objective'
  | 'benchmarkVersions'
  | 'benchmarkVersionBoundary'
  | 'trajectories'
>;

export type FrameAgent = CampaignRecord['agents'][number];
export type FrameMeasurement = CampaignRecord['measurements'][number];

/** Mirrors the backend `ExecutionActivityMode` (`vibesys.events`): what an
 * agent is doing right now, live during a turn rather than frozen at the
 * turn's start. */
type ActivityMode = 'thinking' | 'responding' | 'tool' | 'waiting';

const ACTIVITY_MODES: readonly ActivityMode[] = ['thinking', 'responding', 'tool', 'waiting'];

/** Live retry-budget diagnostics for one workstream, mirroring the backend's
 * `WorkstreamAttemptData` payload. */
export interface WorkstreamAttemptState {
  readonly attempt: number;
  readonly attemptLimit: number;
  readonly refunded: number;
  readonly lastError: string | null;
  readonly setupFailure: boolean;
  readonly repeatedError: boolean;
}

/** One workstream's current live activity, mirroring the backend's
 * `AgentExecutionActivityData` payload. */
export interface WorkstreamActivityState {
  readonly mode: ActivityMode;
  readonly summary: string;
  readonly tool: string | null;
}

/** Mirrors the backend `RunControlTransitionKind` StrEnum (see
 * `vs_runtime.api.infrastructure.RunControlTransitionKind`). A hand-written
 * copy until the backend emits these frames; see the design doc's "Backend
 * path". `steer_consumed`, `paused`, and `stopped` land at an invocation
 * boundary and may carry `agentKind`/`roundLabel`/`executionId`; the other
 * four are request-time and never do. */
export type OperatorAction =
  | 'steer_queued'
  | 'pause_requested'
  | 'resumed'
  | 'stop_requested'
  | 'steer_consumed'
  | 'paused'
  | 'stopped';

const OPERATOR_ACTIONS: readonly OperatorAction[] = [
  'steer_queued',
  'pause_requested',
  'resumed',
  'stop_requested',
  'steer_consumed',
  'paused',
  'stopped',
];

/**
 * Mirrors the backend `JudgeResultData.verdict` Literal. Local to frame
 * parsing; the canonical, externally-consumed alias lives in
 * `replay-scenario.ts` and is re-exported via `campaign-record.ts`.
 */
type JudgeVerdict = 'pass' | 'fail' | 'skipped';
const JUDGE_VERDICTS: readonly JudgeVerdict[] = ['pass', 'fail', 'skipped'];

/**
 * Mirrors the backend `JudgeResultData.skip_reason` Literal. Local to frame
 * parsing; the canonical, externally-consumed alias lives in
 * `replay-scenario.ts` and is re-exported via `campaign-record.ts`.
 */
type JudgeSkipReason = 'blocked' | 'unchanged' | 'not_due';
const JUDGE_SKIP_REASONS: readonly JudgeSkipReason[] = ['blocked', 'unchanged', 'not_due'];

/**
 * One workstream's review assessment: a judge verdict when a review ran, or a
 * skip reason (with empty `analysis`/`feedback`) when it did not. Mirrors the
 * backend `JudgeResultData` payload; `sequence` is the attempt's position in
 * the campaign order, consistent with `FrameWorkstream.firstSequence`/
 * `lastSequence` and `FrameMeasurement.sequence`.
 */
export interface FrameJudgeResult {
  readonly id: string;
  readonly sequence: number;
  readonly workstreamId: string;
  readonly verdict: JudgeVerdict;
  readonly analysis: string;
  readonly feedback: string;
  readonly skipReason: JudgeSkipReason | null;
  readonly implementerOutcome: string;
}

/**
 * One entry on the operator-intervention timeline. Mirrors the fields carried
 * on `server.api.events.RunEvent` for a `CONTROL`/`RUN_STATUS_CHANGED` wire
 * event: `text` is the steer prompt (non-empty only for `steer_queued`),
 * `clientId` is the issuing frontend connection's stable id (null for a
 * boundary-landing transition, which has no requesting client), and
 * `agentKind`/`roundLabel`/`executionId` locate the invocation a
 * boundary-landing transition landed on (null for a request-time
 * transition).
 */
export interface FrameOperatorAction {
  readonly action: OperatorAction;
  readonly text: string;
  readonly agentKind: string | null;
  readonly roundLabel: string | null;
  readonly executionId: string | null;
  readonly clientId: string | null;
  readonly timestamp: string;
}

/**
 * A workstream delta. Unlike the finished-record shape, a live workstream may be
 * in flight: `active` is true, and `finishedAt`/`outcome`/`lastSequence` are not
 * known yet. The fold stores the phase; the view model projects an active
 * workstream's end to "now" so the existing dashboard renders it as active.
 */
export interface FrameWorkstream {
  readonly id: string;
  readonly title: string;
  readonly hypothesis: string;
  readonly startedAt: string;
  readonly firstSequence: number;
  readonly phase: WorkstreamPhase;
  readonly active: boolean;
  readonly finishedAt: string | null;
  readonly lastSequence: number | null;
  readonly outcome: WorkstreamOutcome | null;
  readonly outcomeSummary: string;
}

export type CampaignFrame =
  | {readonly kind: 'campaign-init'; readonly seq: number; readonly header: CampaignHeader}
  | {readonly kind: 'agent-upsert'; readonly seq: number; readonly agent: FrameAgent}
  | {readonly kind: 'workstream-upsert'; readonly seq: number; readonly workstream: FrameWorkstream}
  | {readonly kind: 'measurement'; readonly seq: number; readonly measurement: FrameMeasurement}
  | {
      readonly kind: 'tokens';
      readonly seq: number;
      readonly workstreamId: string;
      readonly tokens: number;
    }
  | {
      readonly kind: 'workstream-attempt';
      readonly seq: number;
      readonly workstreamId: string;
      readonly attempt: WorkstreamAttemptState;
    }
  | {
      readonly kind: 'workstream-activity';
      readonly seq: number;
      readonly workstreamId: string;
      readonly activity: WorkstreamActivityState;
    }
  | {readonly kind: 'status'; readonly seq: number; readonly status: 'active' | 'completed'}
  | ({readonly kind: 'operator-action'; readonly seq: number} & FrameOperatorAction)
  | {readonly kind: 'judge-result'; readonly seq: number; readonly judgeResult: FrameJudgeResult};

type CampaignFrameKind = CampaignFrame['kind'];

const FRAME_KINDS: readonly CampaignFrameKind[] = [
  'campaign-init',
  'agent-upsert',
  'workstream-upsert',
  'measurement',
  'tokens',
  'workstream-attempt',
  'workstream-activity',
  'status',
  'operator-action',
  'judge-result',
];

class FrameError extends Error {}

function fail(path: string, message: string): never {
  throw new FrameError(`${path}: ${message}`);
}

/**
 * A parsed object with the frame fields declared, so property access reads as
 * `object.kind` rather than an index-signature lookup. Mirrors the `JsonObject`
 * approach in `replay-scenario.ts`.
 */
type FrameObject = Record<string, unknown> & {
  kind?: unknown;
  seq?: unknown;
  header?: unknown;
  agent?: unknown;
  workstream?: unknown;
  measurement?: unknown;
  workstreamId?: unknown;
  tokens?: unknown;
  status?: unknown;
  id?: unknown;
  title?: unknown;
  hypothesis?: unknown;
  startedAt?: unknown;
  firstSequence?: unknown;
  phase?: unknown;
  active?: unknown;
  finishedAt?: unknown;
  lastSequence?: unknown;
  outcome?: unknown;
  outcomeSummary?: unknown;
  attempt?: unknown;
  attemptLimit?: unknown;
  refunded?: unknown;
  lastError?: unknown;
  setupFailure?: unknown;
  repeatedError?: unknown;
  activity?: unknown;
  mode?: unknown;
  summary?: unknown;
  tool?: unknown;
  action?: unknown;
  text?: unknown;
  agentKind?: unknown;
  roundLabel?: unknown;
  executionId?: unknown;
  clientId?: unknown;
  timestamp?: unknown;
  judgeResult?: unknown;
  sequence?: unknown;
  verdict?: unknown;
  analysis?: unknown;
  feedback?: unknown;
  skipReason?: unknown;
  implementerOutcome?: unknown;
};

function asObject(value: unknown, path: string): FrameObject {
  if (typeof value !== 'object' || value === null || Array.isArray(value))
    fail(path, 'expected an object');
  return value as FrameObject;
}

function asString(value: unknown, path: string): string {
  if (typeof value !== 'string') fail(path, 'expected a string');
  return value;
}

function asNumber(value: unknown, path: string): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) fail(path, 'expected a finite number');
  return value;
}

function asBoolean(value: unknown, path: string): boolean {
  if (typeof value !== 'boolean') fail(path, 'expected a boolean');
  return value;
}

function member<T extends string>(value: unknown, path: string, allowed: readonly T[]): T {
  const text = asString(value, path);
  if (!allowed.includes(text as T)) fail(path, `expected one of ${allowed.join(', ')}`);
  return text as T;
}

function exactKeys(object: FrameObject, path: string, keys: readonly string[]): void {
  for (const key of Object.keys(object))
    if (!keys.includes(key)) fail(`${path}.${key}`, 'unexpected key');
  for (const key of keys) if (!(key in object)) fail(`${path}.${key}`, 'missing key');
}

function nullableString(value: unknown, path: string): string | null {
  return value === null ? null : asString(value, path);
}

function nullableNumber(value: unknown, path: string): number | null {
  return value === null ? null : asNumber(value, path);
}

function nullableMember<T extends string>(
  value: unknown,
  path: string,
  allowed: readonly T[],
): T | null {
  return value === null ? null : member(value, path, allowed);
}

function parseWorkstream(value: unknown, path: string): FrameWorkstream {
  const object = asObject(value, path);
  exactKeys(object, path, [
    'id',
    'title',
    'hypothesis',
    'startedAt',
    'firstSequence',
    'phase',
    'active',
    'finishedAt',
    'lastSequence',
    'outcome',
    'outcomeSummary',
  ]);
  return {
    id: asString(object.id, `${path}.id`),
    title: asString(object.title, `${path}.title`),
    hypothesis: asString(object.hypothesis, `${path}.hypothesis`),
    startedAt: asString(object.startedAt, `${path}.startedAt`),
    firstSequence: asNumber(object.firstSequence, `${path}.firstSequence`),
    phase: member(object.phase, `${path}.phase`, WORKSTREAM_PHASES),
    active: asBoolean(object.active, `${path}.active`),
    finishedAt: nullableString(object.finishedAt, `${path}.finishedAt`),
    lastSequence: nullableNumber(object.lastSequence, `${path}.lastSequence`),
    outcome:
      object.outcome === null
        ? null
        : member(object.outcome, `${path}.outcome`, ['accepted', 'rejected'] as const),
    outcomeSummary: asString(object.outcomeSummary, `${path}.outcomeSummary`),
  };
}

function parseWorkstreamAttempt(value: unknown, path: string): WorkstreamAttemptState {
  const object = asObject(value, path);
  exactKeys(object, path, [
    'attempt',
    'attemptLimit',
    'refunded',
    'lastError',
    'setupFailure',
    'repeatedError',
  ]);
  return {
    attempt: asNumber(object.attempt, `${path}.attempt`),
    attemptLimit: asNumber(object.attemptLimit, `${path}.attemptLimit`),
    refunded: asNumber(object.refunded, `${path}.refunded`),
    lastError: nullableString(object.lastError, `${path}.lastError`),
    setupFailure: asBoolean(object.setupFailure, `${path}.setupFailure`),
    repeatedError: asBoolean(object.repeatedError, `${path}.repeatedError`),
  };
}

function parseWorkstreamActivity(value: unknown, path: string): WorkstreamActivityState {
  const object = asObject(value, path);
  exactKeys(object, path, ['mode', 'summary', 'tool']);
  return {
    mode: member(object.mode, `${path}.mode`, ACTIVITY_MODES),
    summary: asString(object.summary, `${path}.summary`),
    tool: nullableString(object.tool, `${path}.tool`),
  };
}

function parseJudgeResult(value: unknown, path: string): FrameJudgeResult {
  const object = asObject(value, path);
  exactKeys(object, path, [
    'id',
    'sequence',
    'workstreamId',
    'verdict',
    'analysis',
    'feedback',
    'skipReason',
    'implementerOutcome',
  ]);
  const verdict = member(object.verdict, `${path}.verdict`, JUDGE_VERDICTS);
  const skipReason = nullableMember(object.skipReason, `${path}.skipReason`, JUDGE_SKIP_REASONS);
  if (verdict === 'skipped' && skipReason === null)
    fail(`${path}.skipReason`, 'required when verdict is skipped');
  if (verdict !== 'skipped' && skipReason !== null)
    fail(`${path}.skipReason`, 'must be null unless verdict is skipped');
  return {
    id: asString(object.id, `${path}.id`),
    sequence: asNumber(object.sequence, `${path}.sequence`),
    workstreamId: asString(object.workstreamId, `${path}.workstreamId`),
    verdict,
    analysis: asString(object.analysis, `${path}.analysis`),
    feedback: asString(object.feedback, `${path}.feedback`),
    skipReason,
    implementerOutcome: asString(object.implementerOutcome, `${path}.implementerOutcome`),
  };
}

/**
 * Validate an unknown value as a campaign frame, rejecting an unknown kind,
 * an unexpected or missing key, or a wrong type, and naming the offending path.
 * The payloads that are `CampaignRecord` sub-objects (`header`, `agent`,
 * `measurement`) are carried as-is and checked structurally at the top level;
 * the producer is the record validated by `parseReplayScenario`.
 */
export function parseCampaignFrame(value: unknown): CampaignFrame {
  const object = asObject(value, '$');
  const kind = member(object.kind, '$.kind', FRAME_KINDS);
  const seq = asNumber(object.seq, '$.seq');
  switch (kind) {
    case 'campaign-init': {
      exactKeys(object, '$', ['kind', 'seq', 'header']);
      return {kind, seq, header: asObject(object.header, '$.header') as unknown as CampaignHeader};
    }
    case 'agent-upsert': {
      exactKeys(object, '$', ['kind', 'seq', 'agent']);
      return {kind, seq, agent: asObject(object.agent, '$.agent') as unknown as FrameAgent};
    }
    case 'workstream-upsert': {
      exactKeys(object, '$', ['kind', 'seq', 'workstream']);
      return {kind, seq, workstream: parseWorkstream(object.workstream, '$.workstream')};
    }
    case 'measurement': {
      exactKeys(object, '$', ['kind', 'seq', 'measurement']);
      return {
        kind,
        seq,
        measurement: asObject(object.measurement, '$.measurement') as unknown as FrameMeasurement,
      };
    }
    case 'tokens': {
      exactKeys(object, '$', ['kind', 'seq', 'workstreamId', 'tokens']);
      return {
        kind,
        seq,
        workstreamId: asString(object.workstreamId, '$.workstreamId'),
        tokens: asNumber(object.tokens, '$.tokens'),
      };
    }
    case 'workstream-attempt': {
      exactKeys(object, '$', ['kind', 'seq', 'workstreamId', 'attempt']);
      return {
        kind,
        seq,
        workstreamId: asString(object.workstreamId, '$.workstreamId'),
        attempt: parseWorkstreamAttempt(object.attempt, '$.attempt'),
      };
    }
    case 'workstream-activity': {
      exactKeys(object, '$', ['kind', 'seq', 'workstreamId', 'activity']);
      return {
        kind,
        seq,
        workstreamId: asString(object.workstreamId, '$.workstreamId'),
        activity: parseWorkstreamActivity(object.activity, '$.activity'),
      };
    }
    case 'status': {
      exactKeys(object, '$', ['kind', 'seq', 'status']);
      return {
        kind,
        seq,
        status: member(object.status, '$.status', ['active', 'completed'] as const),
      };
    }
    case 'operator-action': {
      exactKeys(object, '$', [
        'kind',
        'seq',
        'action',
        'text',
        'agentKind',
        'roundLabel',
        'executionId',
        'clientId',
        'timestamp',
      ]);
      return {
        kind,
        seq,
        action: member(object.action, '$.action', OPERATOR_ACTIONS),
        text: asString(object.text, '$.text'),
        agentKind: nullableString(object.agentKind, '$.agentKind'),
        roundLabel: nullableString(object.roundLabel, '$.roundLabel'),
        executionId: nullableString(object.executionId, '$.executionId'),
        clientId: nullableString(object.clientId, '$.clientId'),
        timestamp: asString(object.timestamp, '$.timestamp'),
      };
    }
    case 'judge-result': {
      exactKeys(object, '$', ['kind', 'seq', 'judgeResult']);
      return {kind, seq, judgeResult: parseJudgeResult(object.judgeResult, '$.judgeResult')};
    }
  }
}

export function isTerminalPhase(phase: WorkstreamPhase): boolean {
  return phase === 'evaluated' || phase === 'failed' || phase === 'cancelled';
}
