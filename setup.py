"""Setuptools shim that stages release-owned assets into the wheel.

Project metadata lives in ``pyproject.toml``; this file exists only to hook a
custom ``build_py`` step that copies framework resources and the input SDK.
Setuptools never installs JavaScript dependencies or mutates the checkout.
"""

from __future__ import annotations

import sys
from pathlib import Path

from setuptools import setup
from setuptools.command.build_py import build_py as _build_py
from setuptools.command.egg_info import egg_info as _egg_info

_REPO_ROOT = Path(__file__).parent.resolve()
sys.path.insert(0, str(_REPO_ROOT))
# Build helpers live in packaging/ as top-level modules. There is deliberately no
# packaging/__init__.py: a `packaging` package would shadow the PyPA library.
sys.path.insert(0, str(_REPO_ROOT / "packaging"))

# lint-waiver: LW-008020 [E402]; This standalone bundle adds a sibling module directory to sys.path before importing its modules.
from packaging_support import (  # noqa: E402
    clear_distribution_build_outputs,
    discover_client_workspace_sources,
    discover_distribution_packages,
    is_client_workspace_path,
)

# lint-waiver: LW-008021 [E402]; This standalone bundle adds a sibling module directory to sys.path before importing its modules.
from resources_packaging import stage_resources, stage_sdk  # noqa: E402


class BuildPy(_build_py):
    """Standard ``build_py`` plus staging framework resources and the SDK."""

    def run(self) -> None:
        """Stage build outputs after setuptools copies Python packages."""
        clear_distribution_build_outputs(Path(self.build_lib), self.packages or [])
        super().run()
        vibesys_package_root = Path(self.build_lib) / "vibesys"
        stage_resources(_REPO_ROOT, vibesys_package_root / "_resources", required=True)
        stage_sdk(_REPO_ROOT, vibesys_package_root / "_sdk", required=True)


class EggInfo(_egg_info):
    """Keep the source manifest complete without broadly grafting client state."""

    def find_sources(self) -> None:
        """Replace broad client inputs with tracked, canonical workspace sources."""
        super().find_sources()
        self.filelist.files[:] = [
            path for path in self.filelist.files if not is_client_workspace_path(path)
        ]
        self.filelist.extend(discover_client_workspace_sources(_REPO_ROOT))
        self.filelist.sort()
        self.filelist.remove_duplicates()
        manifest = str(Path(self.egg_info) / "SOURCES.txt")
        content = "# file GENERATED by distutils, do NOT edit\n" + "\n".join(self.filelist.files)
        self.write_file("manifest", manifest, content + "\n")


packages, package_dirs = discover_distribution_packages(_REPO_ROOT)

setup(
    packages=packages,
    package_dir=package_dirs,
    cmdclass={"build_py": BuildPy, "egg_info": EggInfo},
)
