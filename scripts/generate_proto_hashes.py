"""Generate language constants from canonical, package-scoped descriptor sets.

Canonicalization selects only files in the named package, sorts them by proto
path, removes source locations/comments, and serializes using protobuf-py's
field-number order. Imported packages are versioned separately; language plugin
managed options are not applied. Hashes cover the source descriptors, including
validation options, rather than any language's generated representation.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

from protobuf.wkt.google.protobuf.descriptor_pb import FileDescriptorSet

RUN_LOG_MAX_RECORD_BYTES = 1048576
RUN_LOG_MAGIC = "VSRLOG01"


def schema_hash(image: bytes, package: str) -> str:
    """Return SHA-256 of the canonical FileDescriptorSet for a nonempty package."""
    files = [file for file in FileDescriptorSet.from_binary(image).file if file.package == package]
    if not files:
        message = f"Descriptor set has no files in package {package}"
        raise ValueError(message)
    for file in files:
        file.clear_field("source_code_info")
    canonical = FileDescriptorSet(file=sorted(files, key=lambda file: file.name))
    return hashlib.sha256(canonical.to_binary()).hexdigest()


def generate(image: bytes, root: Path) -> None:
    """Write Python, TypeScript, and Go constants from the same two digests."""
    api = schema_hash(image, "vibesys.api.v1")
    store = schema_hash(image, "vibesys.store.v1")
    (root / "libs/vs-proto/src/vs_proto/_generated/schema_hashes.py").write_text(
        '"""Generated by scripts/generate_proto.sh; do not edit."""\n\n'
        f'API_SCHEMA_HASH = "{api}"\nSTORE_SCHEMA_HASH = "{store}"\n'
        f'RUN_LOG_MAX_RECORD_BYTES = {RUN_LOG_MAX_RECORD_BYTES}\nRUN_LOG_MAGIC = b"{RUN_LOG_MAGIC}"\n',
        encoding="utf-8",
    )
    (root / "clients/libs/proto/src/generated/schema-hashes.ts").write_text(
        "// Generated by scripts/generate_proto.sh; do not edit.\n"
        f"export const API_SCHEMA_HASH = '{api}';\nexport const STORE_SCHEMA_HASH = '{store}';\n"
        f"export const RUN_LOG_MAX_RECORD_BYTES = {RUN_LOG_MAX_RECORD_BYTES};\n"
        f"export const RUN_LOG_MAGIC = '{RUN_LOG_MAGIC}';\n",
        encoding="utf-8",
    )
    (root / "gateway/gen/schema_hashes.go").write_text(
        "// Code generated by scripts/generate_proto.sh. DO NOT EDIT.\n\npackage gen\n\n"
        f'const APISchemaHash = "{api}"\nconst StoreSchemaHash = "{store}"\n'
        f'const RunLogMaxRecordBytes = {RUN_LOG_MAX_RECORD_BYTES}\nconst RunLogMagic = "{RUN_LOG_MAGIC}"\n',
        encoding="utf-8",
    )


if __name__ == "__main__":
    generate(Path(sys.argv[1]).read_bytes(), Path(__file__).resolve().parents[1])
