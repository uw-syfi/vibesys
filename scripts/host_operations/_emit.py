def go_registry(operations: tuple[Operation, ...], failures: tuple[str, ...], minimum: str) -> str:
    """Generate the Go decoder/dispatcher factory table and exhaustive failure visitor."""
    lines = [
        "// Code generated by scripts/generate_proto.sh. DO NOT EDIT.",
        "package hostoperations",
        "import (",
        '"fmt"',
        '"time"',
        'hostv1 "github.com/uw-syfi/vibesys/gateway/gen/vibesys/host/v1"',
        '"google.golang.org/protobuf/proto"',
        ")",
        "// MinCheckoutVersion is projected from the host payload descriptor's compatibility policy.",
        f'const MinCheckoutVersion = "{minimum}"',
        "var registry = map[uint32]Operation{",
    ]
    for op in operations:
        p = op.policy
        correlations = ",".join(
            "{"
            "{"
            + ",".join(f'"{s}"' for s in left)
            + "},{"
            + ",".join(f'"{s}"' for s in right)
            + "}}"
            for left, right in op.correlations
        )
        lines += [
            f'{p.operation_id}: {{ID: {p.operation_id}, Name: "{op.name}", RequestTag: {p.request_tag}, ResponseTag: {p.response_tag}, Cap: {p.cap_ms}*time.Millisecond, Grace: {p.grace_ms}*time.Millisecond, Effect: hostv1.OperationEffect({p.effect}), Retry: hostv1.Retry({p.retry}), Executor: hostv1.Executor({p.executor}), Cardinality: hostv1.Cardinality({p.cardinality}), FirstEvent: {p.first_event_ms}*time.Millisecond, Progress: {p.progress_ms}*time.Millisecond, NewRequest: func() proto.Message {{return &hostv1.{op.request}{{}}}}, NewResponse: func() proto.Message {{return &hostv1.{op.response}{{}}}}, Correlations: [][2][]string{{{correlations}}}}},'
        ]
    lines += ["}", "type FailureVisitor[T any] interface {"]
    for name in failures:
        method = "".join(p.title() for p in name.split("_"))
        lines += [f"{method}(*hostv1.OperationFailure) T"]
    lines += [
        "}",
        "func VisitFailure[T any](failure *hostv1.OperationFailure, visitor FailureVisitor[T]) (T,error) {",
        "switch failure.GetCategory() {",
    ]
    for name in failures:
        method = "".join(p.title() for p in name.split("_"))
        lines += [
            f"case hostv1.FailureCategory_FAILURE_CATEGORY_{name}: return visitor.{method}(failure),nil"
        ]
    lines += [
        'default: var zero T; return zero,fmt.Errorf("unknown failure category: %d", failure.GetCategory())',
        "}",
        "}",
        "",
    ]
    return "\n".join(lines)


def _schema_import(operations: tuple[Operation, ...], names: str, module: str) -> list[str]:
    if not operations:
        return []
    return [f"import {{{names}}} from '{module}';"]


def _call_lines(operations: tuple[Operation, ...]) -> list[str]:
    lines: list[str] = []
    for op in operations:
        correlation = repr(
            [
                [[_js_name(n) for n in left], [_js_name(n) for n in right]]
                for left, right in op.correlations
            ]
        )
        lines += [
            f'export function accept{op.name}(input: MessageInitShape<typeof pb.{op.request}Schema>): Accepted<"{op.name}"> {{',
            f"  return accept(operationPolicies.{op.name}, pb.{op.request}Schema, input);",
            "}",
            f'export async function call{op.name}(transport: OperationTransport, request: Accepted<"{op.name}">, signal: OperationSignal): Promise<pb.{op.response}> {{',
            f"  return call(transport, {{policy: operationPolicies.{op.name}, requestSchema: pb.{op.request}Schema, responseSchema: pb.{op.response}Schema, correlations: {correlation}}}, request, signal);",
            "}",
        ]
    return lines


def _accept_lines(operations: tuple[Operation, ...]) -> list[str]:
    lines: list[str] = []
    for op in operations:
        lines += [
            f'export function accept{op.name}(input: MessageInitShape<typeof pb.{op.request}Schema>): Accepted<"{op.name}"> {{',
            f"  return accept(operationPolicies.{op.name}, pb.{op.request}Schema, input);",
            "}",
        ]
    return lines


def typescript_registry(
    operations: tuple[Operation, ...],
    failures: tuple[str, ...],
    admissions: tuple[Operation, ...],
    mutations: tuple[Operation, ...] = (),
    watches: tuple[Operation, ...] = (),
) -> str:
    """Generate opaque accepted constructors, typed calls and exhaustive failures."""
    lines = [
        "// Generated by scripts/generate_proto.sh; do not edit.",
        "import {create, fromBinary, type MessageInitShape, toBinary} from '@bufbuild/protobuf';",
        "import {ReadRequestSchema, ReadResponseSchema} from './vibesys/api/v1/host_read_generated_pb.js';",
        *_schema_import(
            mutations,
            "MutateRequestSchema, MutateResponseSchema",
            "./vibesys/api/v1/host_mutate_generated_pb.js",
        ),
        *_schema_import(
            watches,
            "WatchRequestSchema, WatchResponseSchema",
            "./vibesys/api/v1/host_watch_generated_pb.js",
        ),
        "import * as pb from './vibesys/host/v1/operations_pb.js';",
        "import {FailureCategory, type OperationFailure} from './vibesys/host/v1/failure_pb.js';",
        "import {OperationFailed} from '../operation-failure.js';",
        "import {accept, call, type Accepted, type OperationTransport, type OperationSignal} from '../operations.js';",
        "export const operationPolicies = Object.freeze({",
    ]
    for op in (*operations, *mutations, *watches):
        p = op.policy
        lines += [
            f"  {op.name}: Object.freeze({{name: '{op.name}', id: {p.operation_id}, requestTag: {p.request_tag}, responseTag: {p.response_tag}, capMs: {p.cap_ms}, graceMs: {p.grace_ms}, totalMs: {p.cap_ms + p.grace_ms}, effect: {p.effect}, retry: {p.retry}, executor: {p.executor}, cardinality: {p.cardinality}, firstEventMs: {p.first_event_ms if p.HasField('first_event_ms') else 'undefined'}, progressMs: {p.progress_ms if p.HasField('progress_ms') else 'undefined'}}} as const),"
        ]
    lines += ["});", "export const hostCallBudgets = Object.freeze({"]
    for op in admissions:
        policy = op.policy
        lines += [
            f"  {_js_name(op.slot)}: Object.freeze({{capMs: {policy.cap_ms}, graceMs: {policy.grace_ms}, totalMs: {policy.cap_ms + policy.grace_ms}}} as const),",
        ]
    lines += ["} as const);"]
    lines += _call_lines((*operations, *mutations))
    lines += _accept_lines(watches)
    lines += ["export interface FailureVisitor<T> {"]
    for name in failures:
        lines += [f"  {name.lower()}(failure: OperationFailure): T;"]
    lines += [
        "}",
        "export function visitFailure<T>(failure: OperationFailure, visitor: FailureVisitor<T>): T {",
        "  switch (failure.category) {",
    ]
    for name in failures:
        lines += [f"    case FailureCategory.{name}: return visitor.{name.lower()}(failure);"]
    lines += ['    default: throw new Error("unknown failure category");', "  }", "}"]
    lines += ["export const readBudgets = Object.freeze({"]
    for op in operations:
        policy = op.policy
        lines += [
            f"  {_js_name(op.slot)}: Object.freeze({{capMs: {policy.cap_ms}, graceMs: {policy.grace_ms}, totalMs: {policy.cap_ms + policy.grace_ms}}} as const),",
        ]
    lines += ["} as const);"]
    lines += [
        "export function encodeHostRead(checkout: string, name: string, payload: Uint8Array): Uint8Array {",
        "  switch (name) {",
    ]
    for op in operations:
        lines += [
            f"    case {op.name!r}:",
            "      return toBinary(ReadRequestSchema, create(ReadRequestSchema, {checkout, method: {case: "
            f"{_js_name(op.slot)!r}, value: fromBinary(pb.{op.request}Schema, payload)"
            "}}));",
        ]
    lines += ['    default: throw new Error("unknown read");', "  }", "}"]
    lines += [
        "export function decodeHostRead(name: string, payload: Uint8Array): Uint8Array {",
        "  const response = fromBinary(ReadResponseSchema, payload);",
        "  const result = response.result;",
        '  if (result.case === undefined) throw new Error("host read returned no result");',
        "  if (result.case === 'failure') throw new OperationFailed(result.value.category, result.value.message);",
        "  switch (name) {",
    ]
    for op in operations:
        case = _js_name(op.slot)
        lines += [
            f"    case {op.name!r}:",
            f"      if (result.case !== {case!r}) throw new Error('response correlation mismatch');",
            f"      return toBinary(pb.{op.response}Schema, result.value);",
        ]
    lines += ['    default: throw new Error("unknown read");', "  }", "}", ""]
    lines += _envelope_codecs(
        "Mutate",
        mutations,
        "MutateRequestSchema",
        "MutateResponseSchema",
        "unknown mutation",
    )
    lines += _envelope_codecs(
        "Watch",
        watches,
        "WatchRequestSchema",
        "WatchResponseSchema",
        "unknown watch",
    )
    lines += ["export const mutateBudgets = Object.freeze({"]
    for op in mutations:
        policy = op.policy
        lines += [
            f"  {_js_name(op.slot)}: Object.freeze({{capMs: {policy.cap_ms}, graceMs: {policy.grace_ms}, totalMs: {policy.cap_ms + policy.grace_ms}}} as const),",
        ]
    lines += ["} as const);", "export const watchBudgets = Object.freeze({"]
    for op in watches:
        policy = op.policy
        first = policy.first_event_ms if policy.HasField("first_event_ms") else 0
        progress = policy.progress_ms if policy.HasField("progress_ms") else 0
        lines += [
            f"  {_js_name(op.slot)}: Object.freeze({{capMs: {policy.cap_ms}, graceMs: {policy.grace_ms}, totalMs: {policy.cap_ms + policy.grace_ms}, firstEventMs: {first}, progressMs: {progress}}} as const),",
        ]
    lines += ["} as const);", ""]
    return "\n".join(lines)


def _envelope_codecs(
    kind: str,
    operations: tuple[Operation, ...],
    request_schema: str,
    response_schema: str,
    unknown: str,
) -> list[str]:
    """Encode and decode one closed envelope. Empty families still export a refusing pair."""
    if not operations:
        return [
            f"export function encodeHost{kind}(_checkout: string, _name: string, _payload: Uint8Array): Uint8Array {{",
            f"  throw new Error({unknown!r});",
            "}",
            f"export function decodeHost{kind}(_name: string, _payload: Uint8Array): Uint8Array {{",
            f"  throw new Error({unknown!r});",
            "}",
        ]
    lines = [
        f"export function encodeHost{kind}(checkout: string, name: string, payload: Uint8Array): Uint8Array {{",
        "  switch (name) {",
    ]
    for op in operations:
        case = _js_name(op.slot)
        lines += [
            f"    case {op.name!r}:",
            "      return toBinary("
            f"{request_schema}, create({request_schema}, {{checkout, method: {{case: {case!r}, value: fromBinary(pb.{op.request}Schema, payload)}}}}));",
        ]
    lines += [f"    default: throw new Error({unknown!r});", "  }", "}"]
    lines += [
        f"export function decodeHost{kind}(name: string, payload: Uint8Array): Uint8Array {{",
        f"  const response = fromBinary({response_schema}, payload);",
        "  const result = response.result;",
        f"  if (result.case === undefined) throw new Error({unknown!r});",
        "  if (result.case === 'failure') throw new OperationFailed(result.value.category, result.value.message);",
        "  switch (name) {",
    ]
    for op in operations:
        case = _js_name(op.slot)
        lines += [
            f"    case {op.name!r}:",
            f"      if (result.case !== {case!r}) throw new Error('response correlation mismatch');",
            f"      return toBinary(pb.{op.response}Schema, result.value);",
        ]
    lines += [f"    default: throw new Error({unknown!r});", "  }", "}"]
    return lines


def helper_types(sources: tuple[str, ...], operations: tuple[Operation, ...]) -> str:
    """Derive temporary adapter type narrowing from its existing closed request union."""
    trees = [ast.parse(source) for source in sources]
    requests = next(
        node.value.slice.elts[0]
        for node in trees[0].body
        if isinstance(node, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "HelperRequest" for t in node.targets)
    )
    names = [node.id for node in ast.walk(requests) if isinstance(node, ast.Name)]
    methods = {}
    for tree in trees:
        for node in tree.body:
            if not isinstance(node, ast.ClassDef) or not node.name.endswith("Request"):
                continue
            for field in node.body:
                if (
                    isinstance(field, ast.AnnAssign)
                    and isinstance(field.target, ast.Name)
                    and field.target.id == "type"
                    and isinstance(field.value, ast.Constant)
                ):
                    methods[field.value.value] = node.name
    adapters = tuple(op for op in operations if op.policy.adapter_method)
    read_names = [methods[op.policy.adapter_method] for op in adapters]
    remaining = [name for name in names if name not in read_names]
    return "\n".join(
        [
            HEADER,
            "from typing_extensions import TypeIs",
            "from server.host_api import (" + ", ".join(["HelperRequest", *names]) + ")",
            "REGISTRY_READ_METHODS = frozenset("
            + repr(tuple(op.policy.adapter_method for op in adapters))
            + ")",
            "RegistryReadRequest = " + " | ".join(read_names),
            "UnmigratedHelperRequest = " + " | ".join(remaining),
            "",
            "def is_registry_read(request: HelperRequest) -> TypeIs[RegistryReadRequest]:",
            '    """Narrow by generated routing while preserving exhaustive legacy dispatch."""',
            "    return request.type in REGISTRY_READ_METHODS",
            "",
        ]
    )
