def go_registry(operations: tuple[Operation, ...], failures: tuple[str, ...]) -> str:
    """Generate the Go decoder/dispatcher factory table and exhaustive failure visitor."""
    lines = [
        "// Code generated by scripts/generate_proto.sh. DO NOT EDIT.",
        "package hostoperations",
        "import (",
        '"fmt"',
        '"time"',
        'hostv1 "github.com/uw-syfi/vibesys/gateway/gen/vibesys/host/v1"',
        '"google.golang.org/protobuf/proto"',
        ")",
        "var registry = map[uint32]Operation{",
    ]
    for op in operations:
        p = op.policy
        correlations = ",".join(
            "{"
            "{"
            + ",".join(f'"{s}"' for s in left)
            + "},{"
            + ",".join(f'"{s}"' for s in right)
            + "}}"
            for left, right in op.correlations
        )
        lines += [
            f'{p.operation_id}: {{ID: {p.operation_id}, Name: "{op.name}", RequestTag: {p.request_tag}, ResponseTag: {p.response_tag}, Cap: {p.cap_ms}*time.Millisecond, Grace: {p.grace_ms}*time.Millisecond, Effect: hostv1.Effect({p.effect}), Retry: hostv1.Retry({p.retry}), Executor: hostv1.Executor({p.executor}), Cardinality: hostv1.Cardinality({p.cardinality}), FirstEvent: {p.first_event_ms}*time.Millisecond, NewRequest: func() proto.Message {{return &hostv1.{op.request}{{}}}}, NewResponse: func() proto.Message {{return &hostv1.{op.response}{{}}}}, Correlations: [][2][]string{{{correlations}}}}},'
        ]
    lines += ["}", "type FailureVisitor[T any] interface {"]
    for name in failures:
        method = "".join(p.title() for p in name.split("_"))
        lines += [f"{method}(*hostv1.OperationFailure) T"]
    lines += [
        "}",
        "func VisitFailure[T any](failure *hostv1.OperationFailure, visitor FailureVisitor[T]) (T,error) {",
        "switch failure.GetCategory() {",
    ]
    for name in failures:
        method = "".join(p.title() for p in name.split("_"))
        lines += [
            f"case hostv1.FailureCategory_FAILURE_CATEGORY_{name}: return visitor.{method}(failure),nil"
        ]
    lines += [
        'default: var zero T; return zero,fmt.Errorf("unknown failure category: %d", failure.GetCategory())',
        "}",
        "}",
        "",
    ]
    return "\n".join(lines)


def typescript_registry(operations: tuple[Operation, ...], failures: tuple[str, ...]) -> str:
    """Generate opaque accepted constructors, typed calls and exhaustive failures."""
    lines = [
        "// Generated by scripts/generate_proto.sh; do not edit.",
        "import {type MessageInitShape} from '@bufbuild/protobuf';",
        "import * as pb from './vibesys/host/v1/operations_pb.js';",
        "import {FailureCategory, type OperationFailure} from './vibesys/host/v1/failure_pb.js';",
        "import {accept, call, type Accepted, type OperationTransport, type OperationSignal} from '../operations.js';",
        "export const operationPolicies = {",
    ]
    for op in operations:
        p = op.policy
        lines += [
            f"  {op.name}: {{name: '{op.name}', id: {p.operation_id}, requestTag: {p.request_tag}, responseTag: {p.response_tag}, capMs: {p.cap_ms}, graceMs: {p.grace_ms}, totalMs: {p.cap_ms + p.grace_ms}, effect: {p.effect}, retry: {p.retry}, executor: {p.executor}, cardinality: {p.cardinality}, firstEventMs: {p.first_event_ms if p.HasField('first_event_ms') else 'undefined'}}},"
        ]
    lines += ["} as const;"]
    for op in operations:
        # JS property names come from descriptor snake_case paths.
        def camel(name: str) -> str:
            return name.split("_", maxsplit=1)[0] + "".join(s.title() for s in name.split("_")[1:])

        correlation = repr(
            [
                [[camel(n) for n in left], [camel(n) for n in right]]
                for left, right in op.correlations
            ]
        )
        lines += [
            f'export function accept{op.name}(input: MessageInitShape<typeof pb.{op.request}Schema>): Accepted<"{op.name}"> {{',
            f"  return accept(operationPolicies.{op.name}, pb.{op.request}Schema, input);",
            "}",
            f'export async function call{op.name}(transport: OperationTransport, request: Accepted<"{op.name}">, signal: OperationSignal): Promise<pb.{op.response}> {{',
            f"  return call(transport, {{policy: operationPolicies.{op.name}, requestSchema: pb.{op.request}Schema, responseSchema: pb.{op.response}Schema, correlations: {correlation}}}, request, signal);",
            "}",
        ]
    lines += ["export interface FailureVisitor<T> {"]
    for name in failures:
        lines += [f"  {name.lower()}(failure: OperationFailure): T;"]
    lines += [
        "}",
        "export function visitFailure<T>(failure: OperationFailure, visitor: FailureVisitor<T>): T {",
        "  switch (failure.category) {",
    ]
    for name in failures:
        lines += [f"    case FailureCategory.{name}: return visitor.{name.lower()}(failure);"]
    lines += ['    default: throw new Error("unknown failure category");', "  }", "}", ""]
    return "\n".join(lines)


def helper_types(sources: tuple[str, ...], operations: tuple[Operation, ...]) -> str:
    """Derive temporary adapter type narrowing from its existing closed request union."""
    trees = [ast.parse(source) for source in sources]
    requests = next(
        node.value.slice.elts[0]
        for node in trees[0].body
        if isinstance(node, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "HelperRequest" for t in node.targets)
    )
    names = [node.id for node in ast.walk(requests) if isinstance(node, ast.Name)]
    methods = {}
    for tree in trees:
        for node in tree.body:
            if not isinstance(node, ast.ClassDef) or not node.name.endswith("Request"):
                continue
            for field in node.body:
                if (
                    isinstance(field, ast.AnnAssign)
                    and isinstance(field.target, ast.Name)
                    and field.target.id == "type"
                    and isinstance(field.value, ast.Constant)
                ):
                    methods[field.value.value] = node.name
    read_names = [methods[op.policy.adapter_method] for op in operations]
    remaining = [name for name in names if name not in read_names]
    return "\n".join(
        [
            HEADER,
            "from typing_extensions import TypeIs",
            "from server.host_api import (" + ", ".join(["HelperRequest", *names]) + ")",
            "REGISTRY_READ_METHODS = frozenset("
            + repr(tuple(op.policy.adapter_method for op in operations))
            + ")",
            "RegistryReadRequest = " + " | ".join(read_names),
            "UnmigratedHelperRequest = " + " | ".join(remaining),
            "",
            "def is_registry_read(request: HelperRequest) -> TypeIs[RegistryReadRequest]:",
            '    """Narrow by generated routing while preserving exhaustive legacy dispatch."""',
            "    return request.type in REGISTRY_READ_METHODS",
            "",
        ]
    )
